"""Generate straight-line DFT codelets operating on AVX2 vectors (2 interleaved complex lanes).

Idea I10 (shared partial sums / CSE in fixed linear circuits): we emit three variants of each
radix-R kernel so the benchmark can measure what circuit minimisation buys on real hardware:
  opt   - recursive radix-2 DIF factorisation, trivial twiddles (1, -i, w8) specialised
  plain - same factorisation, but every non-unit twiddle is a generic complex multiply
  naive - dense R x R matrix-vector product (no shared sums)
Odd primes 3, 5, 7 use the symmetric pairing form (a_j = x_j + x_{p-j}, b_j = x_j - x_{p-j}).

Every codelet computes, in place on V x[R], the forward DFT  X_k = sum_j x_j exp(-2 pi i jk/R).
"""
import math
import sys
from pathlib import Path

POW2 = [2, 4, 8, 16, 32]
ODD = [3, 5, 7]


class Emitter:
    def __init__(self):
        self.lines = []
        self.n = 0

    def tmp(self, expr):
        name = f"t{self.n}"
        self.n += 1
        self.lines.append(f"    V {name} = {expr};")
        return name


def const_c(re, im):
    return f"_mm256_setr_pd({re!r}, {im!r}, {re!r}, {im!r})"


def twiddle_expr(e, var, k, R, mode):
    """Return expression for var * exp(-2 pi i k / R)."""
    k %= R
    if k == 0:
        return var
    if mode == "opt":
        if 4 * k == R:
            return e.tmp(f"vmul_mi({var})")
        if 2 * k == R:
            return e.tmp(f"_mm256_xor_pd({var}, _mm256_set1_pd(-0.0))")
        if 4 * k == 3 * R:
            return e.tmp(f"vmul_pi({var})")
        if 8 * k == R:      # (1 - i)/sqrt2 * a = c*(a + (-i a))
            m = e.tmp(f"vmul_mi({var})")
            return e.tmp(f"vscale(vadd({var}, {m}), {math.sqrt(0.5)!r})")
        if 8 * k == 3 * R:  # (-1 - i)/sqrt2 * a = c*((-i a) - a)
            m = e.tmp(f"vmul_mi({var})")
            return e.tmp(f"vscale(vsub({m}, {var}), {math.sqrt(0.5)!r})")
    a = -2 * math.pi * k / R
    return e.tmp(f"vcmul({var}, {const_c(math.cos(a), math.sin(a))})")


def dif(e, xs, mode):
    """Radix-2 DIF on list of variable names; returns outputs in natural order."""
    R = len(xs)
    if R == 1:
        return xs
    h = R // 2
    top, bot = [], []
    for j in range(h):
        top.append(e.tmp(f"vadd({xs[j]}, {xs[j + h]})"))
        d = e.tmp(f"vsub({xs[j]}, {xs[j + h]})")
        bot.append(twiddle_expr(e, d, j, R, mode))
    even = dif(e, top, mode)  # X[2k]
    odd = dif(e, bot, mode)   # X[2k+1]
    out = [None] * R
    for k in range(h):
        out[2 * k] = even[k]
        out[2 * k + 1] = odd[k]
    return out


def naive(e, xs):
    R = len(xs)
    out = []
    for k in range(R):
        acc = xs[0]
        for j in range(1, R):
            term = twiddle_expr(e, xs[j], j * k, R, "plain")
            acc = e.tmp(f"vadd({acc}, {term})")
        out.append(acc)
    return out


def odd_prime(e, xs):
    p = len(xs)
    h = (p - 1) // 2
    a = [e.tmp(f"vadd({xs[j]}, {xs[p - j]})") for j in range(1, h + 1)]
    b = [e.tmp(f"vsub({xs[j]}, {xs[p - j]})") for j in range(1, h + 1)]
    s = xs[0]
    for j in range(h):
        s = e.tmp(f"vadd({s}, {a[j]})")
    out = [None] * p
    out[0] = s
    for k in range(1, h + 1):
        re = xs[0]
        im = None
        for j in range(1, h + 1):
            c = math.cos(2 * math.pi * j * k / p)
            sn = math.sin(2 * math.pi * j * k / p)
            re = e.tmp(f"_mm256_fmadd_pd(_mm256_set1_pd({c!r}), {a[j - 1]}, {re})")
            term = f"_mm256_mul_pd(_mm256_set1_pd({sn!r}), {b[j - 1]})" if im is None else \
                f"_mm256_fmadd_pd(_mm256_set1_pd({sn!r}), {b[j - 1]}, {im})"
            im = e.tmp(term)
        # X_k = re - i*im ; X_{p-k} = re + i*im
        mi = e.tmp(f"vmul_mi({im})")
        out[k] = e.tmp(f"vadd({re}, {mi})")
        out[p - k] = e.tmp(f"vsub({re}, {mi})")
    return out


def codelet(R, mode):
    e = Emitter()
    xs = []
    for j in range(R):
        xs.append(e.tmp(f"x[{j}]"))
    if R in ODD:
        out = odd_prime(e, xs)
    elif mode == "naive":
        out = naive(e, xs)
    else:
        out = dif(e, xs, mode)
    body = "\n".join(e.lines)
    stores = "\n".join(f"    x[{k}] = {out[k]};" for k in range(R))
    return f"static inline void cl_{mode}_{R}(V *restrict x) {{\n{body}\n{stores}\n}}\n"


def main(out):
    parts = ["// SPDX-License-Identifier: GPL-2.0-or-later", "// AUTO-GENERATED by scripts/gen_codelets.py -- do not edit.",
             "#pragma once", '#include "../common/common.h"', ""]
    for mode in ["opt", "plain", "naive"]:
        for R in POW2:
            parts.append(codelet(R, mode))
    for R in ODD:
        parts.append(codelet(R, "opt"))
    # dispatch helper
    parts.append("typedef void (*codelet_fn)(V *restrict);")
    parts.append("static inline codelet_fn get_codelet(int R, int mode) {")
    parts.append("    switch (mode * 100 + R) {")
    for mi, mode in enumerate(["opt", "plain", "naive"]):
        for R in POW2:
            parts.append(f"    case {mi * 100 + R}: return cl_{mode}_{R};")
        for R in ODD:
            parts.append(f"    case {mi * 100 + R}: return cl_opt_{R};")
    parts.append("    default: return 0;\n    }\n}")
    Path(out).write_text("\n".join(parts) + "\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "csrc/dft/codelets_gen.h")
